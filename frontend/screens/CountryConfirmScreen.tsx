export default function CountryConfirmScreen({ navigation }: any) {
  const [selected, setSelected] = useState<string | null>(null);
  const [search, setSearch] = useState('');
  const [saving, setSaving] = useState(false);

  useEffect(() => {
    const locales = Localization.getLocales();
    const deviceRegion = locales[0]?.regionCode;
    const match = COUNTRIES.find((c) => c.code === deviceRegion);
    setSelected(match ? match.code : null);
  }, []);

  const filteredCountries = COUNTRIES.filter((c) =>
    c.name.toLowerCase().includes(search.toLowerCase()),
  );

  async function handleConfirm() {
    if (!selected) return;
    setSaving(true);
    try {
      await updateCountry(selected);
      navigation.replace('MainTabs');
    } catch (err) {
      console.log('Failed to save country:', err);
    } finally {
      setSaving(false);
    }
  }

  return (
    <SafeAreaView style={styles.container}>
      <View style={styles.header}>
        <Text style={styles.title}>Where are you based?</Text>
        <Text style={styles.subtitle}>
          We use this to show you the right features — you can change it later in Settings.
        </Text>
        <TextInput
          style={styles.searchInput}
          placeholder="Search country..."
          placeholderTextColor="#999"
          value={search}
          onChangeText={setSearch}
        />
      </View>

      <FlatList
        data={filteredCountries}
        keyExtractor={(item) => item.code}
        contentContainerStyle={styles.listContainer}
        keyboardShouldPersistTaps="handled"
        renderItem={({ item }) => {
          const isSelected = selected === item.code;
          return (
            <TouchableOpacity
              onPress={() => setSelected(item.code)}
              style={[styles.countryCard, isSelected && styles.countryCardSelected]}
            >
              <Text style={[styles.countryText, isSelected && styles.countryTextSelected]}>
                {item.name}
              </Text>
            </TouchableOpacity>
          );
        }}
      />

      <View style={styles.footer}>
        <TouchableOpacity
          onPress={handleConfirm}
          disabled={!selected || saving}
          style={[styles.button, (!selected || saving) && styles.buttonDisabled]}
        >
          {saving ? (
            <ActivityIndicator color="#fff" />
          ) : (
            <Text style={styles.buttonText}>Confirm</Text>
          )}
        </TouchableOpacity>
      </View>
    </SafeAreaView>
  );
}

